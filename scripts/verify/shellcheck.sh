#!/usr/bin/env bash
# Runs shellcheck over every shell script the repo tracks (*.sh, plus any file with a
# sh/bash shebang) and over the scripts the site generates, with the same `-x -S warning` as
# `make verify`. Findings already in the code are counted per file and code in the .baseline file
# beside this one; the counts must match exactly, so a new finding fails and a fixed one must
# leave the baseline. Generated scripts have no baseline.
set -euo pipefail
export LC_ALL=C

# v0.11.0
image=koalaman/shellcheck@sha256:61862eba1fcf09a484ebcc6feea46f1782532571a34ed51fedf90dd25f925a8d

cd "$(dirname "${BASH_SOURCE[0]}")/../.."
baseline=scripts/verify/shellcheck.baseline
die() { echo "shellcheck: $*" >&2; exit 1; }
[ -f "$baseline" ] || die "baseline missing: $baseline"
for tool in git docker node; do
  command -v "$tool" >/dev/null || die "$tool is not installed"
done

sc() { # sc <dir> <file>...  prints findings; dies unless shellcheck itself ran
  local dir="$1" out rc=0; shift
  out="$(docker run --rm --network none -v "$dir:/mnt:ro" -w /mnt "$image" -x -S warning -f gcc "$@")" || rc=$?
  # 1 is "has findings"; anything else, or 1 with nothing to show, means it did not run properly.
  [ "$rc" -eq 0 ] || { [ "$rc" -eq 1 ] && [ -n "$out" ]; } || die "shellcheck did not run (exit $rc)"
  printf '%s' "$out"
}

listed="$(git ls-files -- '*.sh')"
shebang="$(git grep -InE '^#!.*[/ ](ba|da)?sh( |$)' | awk -F: '$2 == 1 { print $1 }')"
mapfile -t files < <(printf '%s\n%s\n' "$listed" "$shebang" | sort -u | sed '/^$/d')
[ "${#files[@]}" -gt 0 ] || die "found no shell scripts"

rendered="$(mktemp -d)"
trap 'rm -rf "$rendered"' EXIT
node site/src/data/write-fixtures.mjs "$rendered" >/dev/null
generated=("$rendered"/*.sh)
[ -f "${generated[0]}" ] || die "write-fixtures.mjs wrote no scripts"

findings="$(sc "$PWD" "${files[@]}")"
counts="$(sed -nE 's/^([^:]+):[0-9]+:[0-9]+: .*\[(SC[0-9]+)\]$/\1 \2/p' <<<"$findings" |
  sort | uniq -c | awk '{ print $2, $3, $1 }')"
failed=0
if ! delta="$(diff <(grep -v '^#' "$baseline") <(sed '/^$/d' <<<"$counts"))"; then
  failed=1
  echo "shellcheck: findings differ from $baseline ('<' baseline, '>' now: file code count)"
  grep '^[<>]' <<<"$delta"
  while read -r file code; do
    grep -F -- "$file:" <<<"$findings" | grep -F -- "[$code]" || true
  done < <(awk '/^>/ { print $2, $3 }' <<<"$delta")
  echo "Fix new findings (or add a '# shellcheck disable=' with the reason); delete or lower fixed lines."
fi

generated_findings="$(sc "$rendered" "${generated[@]##*/}")"
if [ -n "$generated_findings" ]; then
  failed=1
  echo "shellcheck: findings in scripts generated by site/src/data/stack-template.js:"
  printf '%s\n' "$generated_findings"
fi

[ "$failed" -eq 0 ] || exit 1
echo "shellcheck: ${#files[@]} script(s) and ${#generated[@]} generated, no new findings"
