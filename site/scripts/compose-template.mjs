import { readFileSync, writeFileSync } from 'node:fs';
import { load } from 'js-yaml';

// Browser-safe snapshot of the actual operator files. CI refuses stale snapshots.
const root = new URL('../../', import.meta.url);
const sources = ['deploy/docker-compose.yml', 'deploy/docker-compose.nvidia.yml'];
const data = Object.fromEntries(sources.map((path) => [path, load(readFileSync(new URL(path, root), 'utf8'))]));
const output = '// Generated by npm run compose:sync. Do not edit.\nexport default ' + JSON.stringify(data, null, 2) + ';\n';
const target = new URL('../src/data/compose-template.generated.js', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) {
    throw new Error('Install template drift: run npm run compose:sync in site/ and commit the result.');
  }
} else {
  writeFileSync(target, output);
}
